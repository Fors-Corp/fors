// Frozen machine code for the two hand-written runtime routines
// (`_rt_write_str`, `_rt_write_int`). These never depend on the input
// program, so instead of re-implementing an encoder for the handful of
// extra instruction forms they use (svc, strb, udiv, ...), their bytes
// were assembled ONCE with the system assembler from `RUNTIME_ASM_TEXT`
// below and are baked into the compiler as a static blob. This keeps
// rung 3 free of any external process at compile time (see REPORT.md
// for the reasoning) while rung 1's printer still emits the identical
// text so `cc`/`as` produce the same bytes (verified: `difftest`
// appends this blob and compares against `otool`'s dump of the same
// text, byte for byte).

pub const RUNTIME_ASM_TEXT: &str = r#"
.text
// Hand-emitted runtime: the two library operations the subset supports,
// using the write(2) syscall directly (macOS arm64: x16=4, x0=fd,
// x1=buf, x2=len, svc #0x80). No libc I/O is used.
.globl _rt_write_str
_rt_write_str:
    stp x29, x30, [sp, #-16]!
    mov x29, sp
    mov x2, x1
    mov x1, x0
    mov x0, #1
    mov x16, #4
    svc #0x80
    ldp x29, x30, [sp], #16
    ret

.globl _rt_write_int
_rt_write_int:
    stp x29, x30, [sp, #-16]!
    mov x29, sp
    sub sp, sp, #48
    mov x2, x0
    mov x3, #0
    cmp x2, #0
    b.ge Lwi_pos
    mov x3, #1
    neg x2, x2
Lwi_pos:
    add x4, sp, #38
    mov w7, #10
    strb w7, [sp, #39]
    mov x6, #0
    mov x5, #10
    cmp x2, #0
    b.ne Lwi_loop
    mov w9, #48
    strb w9, [x4]
    sub x4, x4, #1
    add x6, x6, #1
    b Lwi_sign
Lwi_loop:
    cmp x2, #0
    b.eq Lwi_sign
    udiv x8, x2, x5
    msub x9, x8, x5, x2
    add w9, w9, #48
    strb w9, [x4]
    sub x4, x4, #1
    add x6, x6, #1
    mov x2, x8
    b Lwi_loop
Lwi_sign:
    cmp x3, #0
    b.eq Lwi_done
    mov w9, #45
    strb w9, [x4]
    sub x4, x4, #1
    add x6, x6, #1
Lwi_done:
    add x10, x4, #1
    add x6, x6, #1
    mov x0, #1
    mov x1, x10
    mov x2, x6
    mov x16, #4
    svc #0x80
    mov sp, x29
    ldp x29, x30, [sp], #16
    ret
"#;

